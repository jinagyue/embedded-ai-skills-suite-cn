#!/usr/bin/env python3
from __future__ import annotations

import argparse
from pathlib import Path

from _common import find_project_root, load_json, write_json
from analyze_project import analyze
from include_graph import write_dot, write_mermaid


def md_table(headers, rows):
    lines = ['| ' + ' | '.join(headers) + ' |', '| ' + ' | '.join(['---'] * len(headers)) + ' |']
    for row in rows:
        lines.append('| ' + ' | '.join(str(x).replace('|', '\\|') for x in row) + ' |')
    return '\n'.join(lines)


def render_architecture(data: dict) -> str:
    ioc = data.get('ioc') or {}
    mcu = ioc.get('mcu') or {}
    build = data.get('build') or {}
    mods = data.get('modules') or {}
    res = data.get('resource_audit') or {}
    leaks = data.get('hal_leaks') or {}
    deps = data.get('include_graph') or {}

    lines = [
        '# ARCHITECTURE', '',
        '> Generated by embedded-dev-skills-suite V0.2. Review before treating as design authority.', '',
        '## Project Snapshot', '',
        f"- MCU: `{mcu.get('name') or 'unknown'}`",
        f"- Family: `{mcu.get('family') or 'unknown'}`",
        f"- Package: `{mcu.get('package') or 'unknown'}`",
        f"- CubeMX `.ioc`: `{ioc.get('ioc_file') or 'not found'}`",
        f"- Risk score: **{data.get('risk_score', 0)}**", '',
        '## Target Layering', '',
        '```text',
        'L5  App + RTOS composition',
        '      ↓',
        'L4  Business Service',
        '      ↓',
        'L3  Device / Protocol / BSP Service / Board',
        '      ↓',
        'L2  BSP Driver',
        '      ↓',
        'L1  Core / CMSIS / HAL / LL / Vendor',
        '```', '',
        'Horizontal infrastructure: `Middlewares/`, `Common/`, `Config/`, `Tests/`.', '',
        '## Module Inventory', '',
    ]
    rows = []
    for layer, files in mods.items():
        rows.append((layer, len(files), '<br>'.join(f'`{x}`' for x in files[:12]) + ('<br>…' if len(files) > 12 else '')))
    lines.append(md_table(['Layer', 'Files', 'Examples'], rows) if rows else '_No user modules detected._')
    lines += ['', '## Build Backends', '']
    lines.append(md_table(['Backend', 'Detected'], [(k, '<br>'.join(v) if v else '—') for k, v in build.items()]))
    lines += ['', '## Static Architecture Findings', '']
    findings = []
    for f in leaks.get('findings', []):
        findings.append((f.get('severity'), 'HAL/OS leakage', f"`{f.get('file')}:{f.get('line')}` {f.get('message')}"))
    for f in deps.get('violations', []):
        findings.append((f.get('severity'), 'Dependency', f"`{f.get('from')}` → `{f.get('to')}`: {f.get('message')}"))
    for f in res.get('findings', []):
        findings.append((f.get('severity'), f.get('type'), f.get('message')))
    if findings:
        lines.append(md_table(['Severity', 'Type', 'Finding'], findings[:80]))
    else:
        lines.append('No high-level architecture findings detected by heuristics.')
    lines += ['', '## Resource Summary', '']
    if ioc:
        lines.append(f"- Pins: **{len(ioc.get('pins', []))}**")
        lines.append(f"- CubeMX IPs: **{len(ioc.get('ips', []))}**")
        lines.append(f"- DMA entries: **{len(ioc.get('dma', []))}**")
        lines.append(f"- NVIC entries: **{len(ioc.get('nvic', []))}**")
        lines.append(f"- Middleware: {', '.join(ioc.get('middleware', [])) or '—'}")
    else:
        lines.append('- No unique `.ioc` found; source-only analysis was used.')
    lines += ['', '## Dependency Graph', '', 'See `include_graph.mmd` / `include_graph.dot` in this report directory.', '']
    return '\n'.join(lines)


def render_task_design(data: dict) -> str:
    rtos = data.get('rtos') or {}
    lines = ['# TASK_DESIGN', '', '> Generated from CMSIS-RTOS2 / FreeRTOS source heuristics.', '']
    tasks = rtos.get('tasks', [])
    if tasks:
        rows = []
        for t in tasks:
            attrs = t.get('attributes') or {}
            rows.append((
                t.get('name') or attrs.get('name') or t.get('handle'),
                t.get('entry'),
                t.get('stack_size') or attrs.get('stack_size') or 'unknown',
                t.get('priority') or attrs.get('priority') or 'unknown',
                t.get('entry_file') or t.get('file'),
                ', '.join((t.get('calls') or [])[:8]),
            ))
        lines.append(md_table(['Task', 'Entry', 'Stack', 'Priority', 'File', 'Main calls'], rows))
    else:
        lines.append('_No tasks detected._')

    lines += ['', '## IPC Objects', '']
    objects = rtos.get('objects', [])
    if objects:
        lines.append(md_table(['Kind', 'Handle', 'Count', 'Item size', 'File'], [
            (o.get('kind'), o.get('handle'), o.get('count', '—'), o.get('item_size', '—'), o.get('file')) for o in objects
        ]))
    else:
        lines.append('_No RTOS IPC objects detected._')

    lines += ['', '## ISR / RTOS Review', '']
    items = rtos.get('isr_rtos_calls', [])
    if items:
        lines.append(md_table(['Function', 'File', 'RTOS calls', 'Possibly unsafe'], [
            (x['function'], x['file'], ', '.join(x['calls']), ', '.join(x['possibly_unsafe']) or '—') for x in items
        ]))
    else:
        lines.append('No ISR/callback RTOS calls detected by heuristic scanner.')
    lines += ['', '## Design Review Questions', '',
              '- Is each task a concurrent business activity rather than a hardware peripheral?',
              '- Can polling loops be replaced with blocking queues/flags/notifications?',
              '- Are large payloads copied through queues unnecessarily?',
              '- Are task stack sizes verified with high-water-mark measurements?',
              '- Can every external-device wait path time out and degrade gracefully?', '']
    return '\n'.join(lines)


def render_module_map(data: dict) -> str:
    mods = data.get('modules') or {}
    lines = ['# MODULE_MAP', '', '## Layer-to-directory mapping', '',
             '```text',
             'App/       -> L5 product workflow/state machine',
             'RTOS/      -> L5 composition/task entry',
             'Service/   -> L4 business capabilities',
             'Device/    -> L3 concrete external devices',
             'Protocol/  -> L3 frame encode/decode',
             'BSP/Service + BSP/Board + BSP/Port -> L3 platform/resource services',
             'BSP/Driver -> L2 MCU peripheral abstraction',
             'Core/ + Drivers/ -> L1 CubeMX/vendor',
             '```', '', '## Detected files', '']
    for layer, files in mods.items():
        lines.append(f'### {layer}')
        lines.append('')
        for f in files:
            lines.append(f'- `{f}`')
        if not files:
            lines.append('- _none_')
        lines.append('')
    lines += ['## Migration Priorities', '',
              '1. Move protocol parsing out of task entry functions.',
              '2. Remove direct HAL access from App/Service/Protocol.',
              '3. Replace mutable `extern` sharing with APIs/queues/events.',
              '4. Keep CubeMX generated code as thin glue.',
              '5. Split only where responsibilities are genuinely different; avoid empty layers.', '']
    return '\n'.join(lines)


def main() -> None:
    ap = argparse.ArgumentParser(description='Generate ARCHITECTURE.md + TASK_DESIGN.md + MODULE_MAP.md')
    ap.add_argument('project', nargs='?', default='.')
    ap.add_argument('--output-dir', default=None)
    ap.add_argument('--model', help='reuse existing project_model.json instead of rescanning')
    ap.add_argument('--strict-osal', action='store_true')
    args = ap.parse_args()
    root = find_project_root(args.project)
    out = Path(args.output_dir).resolve() if args.output_dir else root / '.embedded-ai' / 'reports'
    out.mkdir(parents=True, exist_ok=True)
    if args.model:
        data = load_json(Path(args.model))
    else:
        data = analyze(root, strict_osal=args.strict_osal)
        write_json(root / '.embedded-ai' / 'project_model.json', data)
    (out / 'ARCHITECTURE.md').write_text(render_architecture(data), encoding='utf-8')
    (out / 'TASK_DESIGN.md').write_text(render_task_design(data), encoding='utf-8')
    (out / 'MODULE_MAP.md').write_text(render_module_map(data), encoding='utf-8')
    write_dot(data['include_graph'], out / 'include_graph.dot')
    write_mermaid(data['include_graph'], out / 'include_graph.mmd')
    print(f'Generated: {out / "ARCHITECTURE.md"}')
    print(f'Generated: {out / "TASK_DESIGN.md"}')
    print(f'Generated: {out / "MODULE_MAP.md"}')
    print(f'Generated: {out / "include_graph.mmd"}')


if __name__ == '__main__':
    main()
